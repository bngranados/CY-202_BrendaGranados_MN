# Contador For

# Objetivo: Usar ciclos for


# Mostrar números del 1 al 100
for contador in range(1, 101):
    print(contador)
    
# Mostrar números del 100 al 1
for contador in range(100, 0, -1):
    print(contador)

# Mostrar números del 100 al 1 de 10
for contador in range(100, 0, -10):
    print(contador)
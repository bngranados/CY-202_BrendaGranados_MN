# Elimianr elemento usando remove()

# Crear una lista de animales

animales = ["Perro", "Gato", "Huron", "Hamster", "Conejo"]

# Mostrar la lista 
print("Lista: ", animales)

# Solicitar un animal a eliminar
animal = input("Ingrese un animal: ")

# Eliminar usando remove()
animales.remove(animal)

# Mostrar la lista actualizada 
print("Animales:", animales)
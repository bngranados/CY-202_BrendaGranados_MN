# Ciclos While

# Objetivo: Usar ciclos while

# Inicializar el contador
contador = 1

# Mostrar los numeros del 1 al 100
while contador <= 100:
    print(contador)
    contador += 1
    
# Mostrar del 100 al 1 
contador = 100
while contador >= 1:
    print(contador)
    contador -= 1
    
# Mostrar números del 100 al 1 de 10
contador = 100
while contador >= 1:
    print(contador)
    contador -= 10